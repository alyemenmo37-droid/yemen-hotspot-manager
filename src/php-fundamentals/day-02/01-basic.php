// ═══════════════════════════════════════
// 1. أبسط دالة
// ═══════════════════════════════════════
function greet() {
    echo "مرحباً!\n";
}

greet();  // استدعاء الدالة
greet();  // يمكن استدعاؤها عدة مرات


// ═══════════════════════════════════════
// 2. دالة مع parameter
// ═══════════════════════════════════════
function greetPerson($name) {
    echo "مرحباً يا $name!\n";
}

greetPerson("محمد");
greetPerson("أحمد");


// ═══════════════════════════════════════
// 3. دالة مع default value
// ═══════════════════════════════════════
function greetWithTime($name, $timeOfDay = "صباح") {
    echo "$timeOfDay الخير يا $name!\n";
}

greetWithTime("علي");              // صباح الخير يا علي
greetWithTime("سارة", "مساء");      // مساء الخير يا سارة


// ═══════════════════════════════════════
// 4. دالة ترجع قيمة
// ═══════════════════════════════════════
function add($a, $b) {
    return $a + $b;
}

$result = add(5, 3);
echo "5 + 3 = $result\n";

// يمكن استخدامها في تعبير مباشر
echo "10 + 20 = " . add(10, 20) . "\n";


// ═══════════════════════════════════════
// 5. دالة بسيطة لـ Hotspot
// ═══════════════════════════════════════
function formatSpeed($upload, $download) {
    return "$upload/$download";
}

echo "السرعة: " . formatSpeed("256k", "1M") . "\n";
